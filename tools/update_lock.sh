#!/usr/bin/env bash
# Regenerates requirements.lock (hash-pinned, valid for Python 3.11 and newer) from requirements.txt.
#   bash tools/update_lock.sh            needs uv: https://docs.astral.sh/uv/
# Run it after changing requirements.txt (for example on a Dependabot pull request), then commit both
# files. The server installs the new libraries the next time deploy/update.sh runs.
set -euo pipefail
cd "$(dirname "$0")/.."
command -v uv >/dev/null || { echo "uv is not installed (pipx install uv, or see https://docs.astral.sh/uv/)"; exit 1; }
{
  echo "# Hash-pinned lock for requirements.txt, valid for Python 3.11+ (generated by tools/update_lock.sh)."
  echo "# Install with: pip install --require-hashes --no-deps -r requirements.lock"
  uv pip compile requirements.txt --universal --python-version 3.11 --generate-hashes --no-header -q -o -
} > requirements.lock.new
mv requirements.lock.new requirements.lock
echo "requirements.lock updated:"
grep -E '^[a-z0-9].*==' requirements.lock | sed 's/ \\$//'
